#!/usr/bin/env python3
"""
Script to enhance training dataset captions using OpenAI API.

Usage:
    export OPENAI_API_KEY="your-key-here"
    python enhance_dataset.py

Requirements:
    pip install openai
"""

import json
import base64
import asyncio
import logging
from pathlib import Path
from typing import Dict, List, Optional
from openai import AsyncOpenAI
import os

# --------------------------- Logging ---------------------------------

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(message)s"
)
LOG = logging.getLogger("dataset_enhancer")

# --------------------------- Constants -------------------------------

SYSTEM_PROMPT = """# Image Caption Enhancement Task

You will review and enhance captions created by human labelers for an image generation training dataset. Your task is to either confirm the caption is high quality or improve it.

## Input Format
You will receive:
- The image
- The human labeler's caption containing:
  - Text description
  - Shot size
  - Shot framing  
  - Shot angle
  - Scene location

## Your Task

Evaluate and enhance the **text description**, **shot size**, **shot framing**, and **shot angle**. The **scene location** is assumed correct and should NOT be critiqued.

### 1. Text Description Guidelines

**What to describe:**
- All important and visible elements in the frame
- Character actions, expressions, and interactions
- The spatial relationships between subjects (e.g., "Bob leans toward Alice as they both laugh" rather than "Bob laughs. Alice laughs.")
- Relevant foreground details and focal points

**What NOT to describe:**
- Events that happened in the past or future
- Things outside the frame
- What characters might be saying
- Scene/background details (lighting, weather, interior decoration, background objects) UNLESS they are a clear focus or a character is directly interacting with them
- Day/night or inside/outside indicators (these are handled separately)
- Character physical appearance (handled by character tags - see below)

**Character Naming Convention:**
Characters are referenced by **first name with a descriptive tag** on their first mention, like: `"Minami (energetic girl with green hair)"`. This tag:
- Was generated by AI as part of our pipeline
- Helps the image model identify characters (character reference images are provided separately as context)
- Should be **preserved** in your enhanced caption
- Only appears the **first time** the character is mentioned; subsequent mentions use the name only

**You may minimally tweak the character tag description IF:**
- Gender can be more specific and is obvious (e.g., "person" → "young woman")
- The character is a humanoid creature described as "person" (e.g., "person" → "foxgirl", "horned demon", etc.)
- Distinct constant features are missing (e.g., "long beard", "elderly")

**Do NOT include in character tags:**
- Eye color
- Outfit/clothing details
- Emotions or actions
- Variable physical features

Keep tags to one concise sentence describing obvious, constant physical features.

**Important context:** Character reference images and recent scene shots are provided to the image generation model separately. This means:
- Character appearance details come from reference images, not your text
- Scene details come from context images, not extensive text descriptions
- Your text description focuses on what's happening, not exhaustive visual details

### 2. Shot Size Options
- Establishing Shot
- Master Shot
- Wide Shot
- Full Shot
- Medium Shot
- Close Up
- Extreme Close Up

### 3. Shot Framing Options
- Single / Single (Dirty)
- Two Shot / Two Shot (Dirty)
- Three Shot / Three Shot (Dirty)
- Four Shot / Four Shot (Dirty)
- Five Shot / Five Shot (Dirty)
- Crowd Shot
- Over the Shoulder (prioritize this if applicable, even if multiple characters are visible)
- Insert Shot

Note: "Dirty" shots (with foreground elements partially obscuring the frame) were not available to human labelers, so you may add this designation where appropriate.

### 4. Shot Angle Options
- Low Angle
- High Angle
- Overhead
- Eye Level
- Shoulder Level
- Hip Level
- Ground Level

## Enhancement Priorities

Focus on improving:
1. **Accuracy** - Correct any factual errors about what's visible
2. **Completeness** - Add important missing details
3. **Clarity** - Rewrite awkward or unclear descriptions
4. **Relationships** - Better describe how subjects interact and relate spatially
5. **Precision** - Use more specific and accurate language where the labeler was vague

Remember: This caption will be used to train an image generation model. Prioritize details that would help the model recreate the image accurately, focusing on composition, action, and interaction rather than exhaustive visual cataloging.

## Output Format

You must respond with a JSON object containing exactly these fields:
{
  "text_description": "enhanced description here",
  "shot_size": "Shot Size",
  "shot_framing": "Shot Framing",
  "shot_angle": "Shot Angle"
}

If the original caption is already high quality, return the original values unchanged."""

DATA_DIR = Path("dataset")
INPUT_METADATA = DATA_DIR / "metadata.json"
OUTPUT_METADATA = DATA_DIR / "enhanced_metadata.json"
PARTIAL_METADATA = DATA_DIR / "enhanced_metadata_partial.json"

MAX_CONCURRENT = 100
MAX_RETRIES = 3
RETRY_DELAY = 2  # seconds

# --------------------------- Helper Functions ------------------------

def encode_image(image_path: Path) -> str:
    """Encode image to base64."""
    with open(image_path, "rb") as f:
        return base64.b64encode(f.read()).decode('utf-8')

def parse_prompt(prompt: str) -> Dict:
    """
    Parse prompt to extract structured fields.
    
    Format: "Create the next shot in the sequence: [description], [shot_size], [shot_framing], [shot_angle]. [scene_info]"
    Returns: dict with all fields
    """
    # Remove the prefix
    content = prompt.replace("Create the next shot in the sequence: ", "")
    
    # Find scene (always ". Same scene:" or ". New scene:")
    if ". Same scene:" in content:
        idx = content.rindex(". Same scene:")
        description_part = content[:idx]
        scene_location = content[idx + 2:]  # Skip ". "
    elif ". New scene:" in content:
        idx = content.rindex(". New scene:")
        description_part = content[:idx]
        scene_location = content[idx + 2:]
    else:
        # Fallback if format is unexpected
        description_part = content
        scene_location = ""
    
    # Last 3 comma-separated parts are: shot_size, shot_framing, shot_angle
    parts = description_part.split(", ")
    if len(parts) >= 3:
        shot_angle = parts[-1]
        shot_framing = parts[-2]
        shot_size = parts[-3]
        text_description = ", ".join(parts[:-3])
    else:
        # Fallback if parsing fails
        text_description = description_part
        shot_size = ""
        shot_framing = ""
        shot_angle = ""
    
    return {
        "text_description": text_description,
        "shot_size": shot_size,
        "shot_framing": shot_framing,
        "shot_angle": shot_angle,
        "scene_location": scene_location
    }

def reconstruct_prompt(text_description: str, shot_size: str, shot_framing: str, 
                       shot_angle: str, scene_location: str) -> str:
    """Reconstruct full prompt in the same format as original."""
    description_with_metadata = f"{text_description}, {shot_size}, {shot_framing}, {shot_angle}"
    return f"Create the next shot in the sequence: {description_with_metadata}. {scene_location}"

async def enhance_sample(client: AsyncOpenAI, sample: Dict, data_dir: Path, 
                        semaphore: asyncio.Semaphore) -> Optional[Dict]:
    """Enhance a single sample using OpenAI API."""
    async with semaphore:
        for attempt in range(MAX_RETRIES):
            try:
                # Parse original prompt
                original_prompt = sample['prompt']
                parsed = parse_prompt(original_prompt)
                
                # Prepare images
                output_image_path = data_dir / sample['image']
                output_image_b64 = encode_image(output_image_path)
                
                # Build message content with all images
                labeler_response = f"{parsed['text_description']}, {parsed['shot_size']}, {parsed['shot_framing']}, {parsed['shot_angle']}, {parsed['scene_location']}"
                content = [
                    {"type": "text", "text": f"Here is the labeler's response for the image:\n{labeler_response}"}
                ]
                
                # Add context images if they exist
                for edit_img in sample.get('edit_image', []):
                    edit_img_path = data_dir / edit_img
                    if edit_img_path.exists():
                        edit_img_b64 = encode_image(edit_img_path)
                        content.append({
                            "type": "image_url",
                            "image_url": {"url": f"data:image/jpeg;base64,{edit_img_b64}"}
                        })
                
                # Add output image (the one being captioned)
                content.append({
                    "type": "image_url",
                    "image_url": {"url": f"data:image/jpeg;base64,{output_image_b64}"}
                })
                
                # Call API
                response = await client.chat.completions.create(
                    model="gpt-5",
                    messages=[
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": content}
                    ],
                    response_format={"type": "json_object"},
                    max_completion_tokens=10000,
                )
                
                # Get response content
                response_content = response.choices[0].message.content
                
                # Log the raw response for debugging
                LOG.debug(f"Raw API response for {sample['image']}: {response_content}")
                
                # Parse response
                try:
                    result = json.loads(response_content)
                except json.JSONDecodeError as e:
                    LOG.error(f"Failed to parse JSON for {sample['image']}. Raw response: {response_content[:500]}")
                    raise
                
                # Reconstruct prompt
                enhanced_prompt = reconstruct_prompt(
                    result['text_description'],
                    result['shot_size'],
                    result['shot_framing'],
                    result['shot_angle'],
                    parsed['scene_location']
                )
                
                # Return enhanced sample in same format
                return {
                    "image": sample['image'],
                    "prompt": enhanced_prompt,
                    "edit_image": sample['edit_image']
                }
                
            except Exception as e:
                if attempt < MAX_RETRIES - 1:
                    wait_time = RETRY_DELAY * (2 ** attempt)
                    LOG.warning(f"Error processing {sample['image']}: {e}. Retrying in {wait_time}s...")
                    await asyncio.sleep(wait_time)
                else:
                    LOG.error(f"Failed to process {sample['image']} after {MAX_RETRIES} attempts: {e}")
                    return None
        
        return None

def load_partial_results() -> Dict[str, Dict]:
    """Load partial results if they exist."""
    if PARTIAL_METADATA.exists():
        with open(PARTIAL_METADATA, 'r') as f:
            data = json.load(f)
            # Create lookup by image path
            return {item['image']: item for item in data}
    return {}

def save_partial_results(results: List[Dict]):
    """Save partial results incrementally."""
    with open(PARTIAL_METADATA, 'w') as f:
        json.dump(results, f, indent=2, ensure_ascii=False)

async def main():
    """Main processing function."""
    
    # Load API key
    api_key = os.environ.get("OPENAI_API_KEY")
    if not api_key:
        LOG.error("OPENAI_API_KEY environment variable not set")
        return
    
    client = AsyncOpenAI(api_key=api_key)
    
    # Load input metadata
    LOG.info(f"Loading metadata from {INPUT_METADATA}")
    with open(INPUT_METADATA, 'r') as f:
        samples = json.load(f)
    
    LOG.info(f"Found {len(samples)} samples to process")
    
    # Load partial results if resuming
    completed = load_partial_results()
    LOG.info(f"Found {len(completed)} already completed samples")
    
    # Filter out already completed
    remaining = [s for s in samples if s['image'] not in completed]
    LOG.info(f"{len(remaining)} samples remaining to process")
    
    if not remaining:
        LOG.info("All samples already processed!")
        # Save final output
        final_results = list(completed.values())
        with open(OUTPUT_METADATA, 'w') as f:
            json.dump(final_results, f, indent=2, ensure_ascii=False)
        return
    
    # Process with concurrency
    semaphore = asyncio.Semaphore(MAX_CONCURRENT)
    all_results = list(completed.values())
    
    LOG.info(f"Starting enhancement with {MAX_CONCURRENT} concurrent requests...")
    
    # Process in batches for incremental saving
    batch_size = 50
    for i in range(0, len(remaining), batch_size):
        batch = remaining[i:i+batch_size]
        
        # Process batch
        tasks = [enhance_sample(client, sample, DATA_DIR, semaphore) for sample in batch]
        batch_results = await asyncio.gather(*tasks)
        
        # Add successful results
        for sample, result in zip(batch, batch_results):
            if result:
                all_results.append(result)
            else:
                # Keep original if enhancement failed
                LOG.warning(f"Keeping original for failed sample: {sample['image']}")
                all_results.append(sample)
        
        # Save partial progress
        save_partial_results(all_results)
        LOG.info(f"Progress: {len(all_results)}/{len(samples)} samples processed")
    
    # Save final output
    LOG.info(f"Saving final results to {OUTPUT_METADATA}")
    with open(OUTPUT_METADATA, 'w') as f:
        json.dump(all_results, f, indent=2, ensure_ascii=False)
    
    # Clean up partial file
    if PARTIAL_METADATA.exists():
        PARTIAL_METADATA.unlink()
    
    LOG.info("Enhancement complete!")

if __name__ == "__main__":
    asyncio.run(main())